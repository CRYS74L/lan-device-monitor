import { readFile, writeFile, mkdir, copyFile } from "node:fs/promises";
import { createRequire } from "node:module";
import { resolve, join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const modules = resolve(process.argv[2] || join(root, ".tools/echarts-integration/deps/node_modules"));
const require = createRequire(join(modules, "echarts/package.json"));
for (const [name, version] of [["echarts", "6.0.0"], ["esbuild", "0.25.12"]]) {
  const actual = JSON.parse(await readFile(join(modules, name, "package.json"))).version;
  if (actual !== version) throw new Error(`Expected ${name}@${version}; found ${actual}`);
}
const { build } = require(join(modules, "esbuild"));
await build({
  entryPoints: [join(root, "scripts/echarts-curve-entry.js")],
  nodePaths: [modules], bundle: true, format: "esm", platform: "browser",
  target: "es2020", minify: true, legalComments: "inline",
  outfile: join(root, "src/LanDeviceMonitor.App/Web/echarts-curve.js"),
  banner: { js: "// Apache ECharts 6.0.0 original ECPolyline; smooth=0.5.\n// Generated by scripts/build-echarts-curves.mjs. See ThirdParty/echarts for licenses and NOTICE." },
});
const target = join(root, "src/LanDeviceMonitor.App/ThirdParty/echarts");
await mkdir(target, { recursive: true });
for (const [source, output] of [["echarts/LICENSE", "LICENSE"], ["echarts/NOTICE", "NOTICE"], ["zrender/LICENSE", "zrender-LICENSE"], ["tslib/LICENSE.txt", "tslib-LICENSE"]])
  await copyFile(join(modules, source), join(target, output));
console.log("Built ECharts 6.0.0 curve module and copied upstream license notices.");
